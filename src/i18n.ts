export type MessageKey = keyof typeof messages['zh-CN'];

export function getLanguage(): Language {
  const saved = localStorage.getItem('language') || navigator.language || 'zh-CN';
  return saved.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function useLanguage(): Language {
  const [language, setLanguage] = useState<Language>(() => getLanguage());

  useEffect(() => {
    const onStorage = (event: StorageEvent) => {
      if (event.key === 'language') setLanguage(getLanguage());
    };
    window.addEventListener('storage', onStorage);
    return () => window.removeEventListener('storage', onStorage);
  }, []);

  return language;
}

export function createTranslator(language: Language) {
  return (key: MessageKey) => messages[language][key] || messages['zh-CN'][key] || key;
}
